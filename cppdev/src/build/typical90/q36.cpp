void solve(){
  ll n, q; cin >> n >> q;

  vector<ll> u(n);
  vector<ll> v(n);
  rep(i, n){
    ll x, y; cin >> x >> y;
    u.at(i) = x + y;
    v.at(i) = x - y;
  }

  ll u_ma = *max_element(u.begin(), u.end());
  ll u_mi = *min_element(u.begin(), u.end());
  ll v_ma = *max_element(v.begin(), v.end());
  ll v_mi = *min_element(v.begin(), v.end());

  while(q--){
    ll qi; cin >> qi;
    qi--;

    ll cand1 = abs(u_ma - u.at(qi));
    ll cand2 = abs(u_mi - u.at(qi));
    ll cand3 = abs(v_ma - v.at(qi));
    ll cand4 = abs(v_mi - v.at(qi));

    ll ans = max(cand1, max(cand2, max(cand3, cand4)));
    cout << ans << endl;
  }
}

int main() {

  solve();

  return 0;
}
